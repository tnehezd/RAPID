class RadiativeSimulationTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.directory = Path(self.temporary.name)
        self.counter = 0

    def run_simulation(self, *extra, binary=BINARY):
        self.counter += 1
        output = self.directory / f"run_{self.counter}"
        mass_arguments = [] if "-disk_mass" in extra else ["-sigma0_init", "1e-5"]
        command = [
            str(binary), "-drift", "0", "-growth", "0", "-twopop", "0",
            "-n", "48", "-ri", "1", "-ro", "10", *mass_arguments,
            "-alpha_init", "0.003", "-rdzei", "2.7", "-rdzeo", "6",
            "-drdzei", "1", "-drdzeo", "1", "-amod", "0.01",
            "-density_floor", "1e-20", "-tmax", "10", "-outfreq", "5",
            "-o", str(output), "-no_panels", *extra,
        ]
        process = subprocess.run(
            command, cwd=ROOT, env={**os.environ, "OMP_NUM_THREADS": "2"},
            capture_output=True, text=True, timeout=120,
        )
        self.assertEqual(process.returncode, 0, process.stdout + process.stderr)
        return output

    def test_dust_growth_and_initial_drift_diagnostic(self):
        for model in ("lociso", "radiative_energy"):
            for grid in ("linear", "logarithmic"):
                for count in (24, 48, 96):
                    with self.subTest(model=model, grid=grid, count=count):
                        output = self.run_simulation(
                            "-thermal_model", model, "-grid_type", grid,
                            "-drift", "1", "-growth", "1", "-ndust", str(count),
                            "-largesize", "0.01", "-tmax", "1", "-outfreq", "1",
                        )
                        drift_file = output / "drift_timecale.dat"
                        lines = drift_file.read_text().splitlines()
                        self.assertTrue(lines[0].startswith("####"))
                        self.assertIn("Generated by Dust Drift Simulation", lines[1])
                        self.assertIn("Version:", lines[2])
                        self.assertTrue(any("Direction: -1 inward (toward star)" in line
                                            for line in lines))
                        column_header = next(line for line in lines
                                             if line.startswith("# Population ") and "Index" in line)
                        self.assertEqual(column_header.split(), [
                            "#", "Population", "Index", "Radius_AU", "Particle_size_cm",
                            "Stokes", "V_radial_AU_yr", "Drift_time_yr", "Direction",
                        ])
                        row = next(line for line in lines if line and not line.startswith("#"))
                        self.assertEqual(
                            [match.start() for match in re.finditer(r"\S+", row)],
                            [match.start() for match in re.finditer(r"\S+", column_header)][1:],
                        )
                        initial = np.loadtxt(drift_file)
                        self.assertEqual(initial.shape, (count, 8))
                        np.testing.assert_array_equal(initial[:, 0], 1)
                        np.testing.assert_array_equal(initial[:, 1], np.arange(count))
                        np.testing.assert_allclose(initial[:, 3], .01, rtol=1e-12)
                        self.assertTrue(np.all(initial[:, 4] >= 0))
                        moving = initial[:, 5] != 0
                        np.testing.assert_allclose(initial[moving, 6],
                                                   initial[moving, 2] / abs(initial[moving, 5]))
                        np.testing.assert_array_equal(initial[:, 7], np.sign(initial[:, 5]))
                        self.assertTrue(np.all(np.isinf(initial[~moving, 6])))
                        snapshots = sorted((output / "LOGS").glob("dust_size_evolution_*.dat"))
                        self.assertGreaterEqual(len(snapshots), 2)
                        sizes = np.loadtxt(snapshots[-1])
                        self.assertTrue(np.all(np.isfinite(sizes)))
                        self.assertTrue(np.all(sizes[:, -1] > 0))

    def test_depleted_prescribed_disk_selects_cold_equilibrium(self):
        sigma_code = 8.86918308e-8 * 1.496e13 ** 2 / 1.989e33
        for model in ("radiative", "radiative_energy"):
            for grid in ("linear", "logarithmic"):
                with self.subTest(model=model, grid=grid):
                    boundary = "outflow" if model == "radiative_energy" else "zero_gradient"
                    output = self.run_simulation(
                        "-thermal_model", model, "-grid_type", grid,
                        "-sigma0_init", str(sigma_code), "-index_init", "0",
                        "-n", "500", "-ro", "50", "-rdzeo", "24",
                        "-irradiation_model", "prescribed", "-irradiation_luminosity", "1",
                        "-irradiation_factor", ".05", "-inner_bc", boundary,
                        "-outer_bc", boundary, "-evol", "0", "-tmax", "0",
                    )
                    snapshots = sorted((output / "LOGS").glob("temperature_profile_*.dat"))
                    self.assertGreaterEqual(len(snapshots), 1)
                    for snapshot in snapshots:
                        data = np.loadtxt(snapshot)
                        self.assertEqual(data.shape, (500, 9))
                        self.assertTrue(np.all(np.isfinite(data)))
                        self.assertTrue(np.all((data[:, 1] > 10) & (data[:, 1] < 200)))
                    initial = np.loadtxt(snapshots[0])
                    if grid == "linear":
                        self.assertGreater(initial[3, 1], 163)
                        self.assertLess(initial[3, 1], 164)
                    if model == "radiative":
                        tau_eff = .375 * initial[:, 6] + math.sqrt(3) / 4 + .25 / initial[:, 6]
                        tirr = (.05 * 3.828e33 /
                                (4 * math.pi * 5.670374419e-5 *
                                 (initial[:, 0] * 1.496e13) ** 2)) ** .25
                        flux = (2 * 5.670374419e-5 *
                                (initial[:, 1] ** 4 + 10 ** 4 + tirr ** 4) / tau_eff)
                        tolerance = (1e-8 * np.maximum(abs(initial[:, 8]), initial[:, 7]) +
                                     64 * np.finfo(float).eps * flux)
                        self.assertTrue(np.all(abs(initial[:, 8] - initial[:, 7]) <= 1.01 * tolerance))

