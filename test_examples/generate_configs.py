"""Generate and run the 80-case matrix, using at most 40 OpenMP threads total."""

import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
from itertools import product
import os
from pathlib import Path
import subprocess
import sys
import time

import yaml


def generate_configs(directory):
    cases = ("lociso", "radiative_prescribed", "radiative_geometry",
             "energy_prescribed", "energy_geometry")
    paths = []
    for dust, case, photoev, sg, grid in product(
            (False, True), cases, (False, True), (False, True), ("linear", "logarithmic")):
        suffix = ("dust_" if dust else "") + case
        name = (("photoev_" if photoev else "no_photoev_") +
                ("sg_" if sg else "no_sg_") + suffix +
                ("_log" if grid == "logarithmic" else ""))
        energy = case.startswith("energy_")
        thermal = {"model": "radiative_energy" if energy else
                   "lociso" if case == "lociso" else "radiative"}
        if case != "lociso":
            thermal.update(mean_molecular_weight=2.34, background_temperature_k=10.0,
                           minimum_temperature_k=1.0, maximum_temperature_k=1500.0,
                           irradiation_luminosity_lsun=1.0,
                           irradiation_model="geometry" if case.endswith("geometry") else "prescribed")
            if energy:
                thermal["gamma"] = 1.4
            if case.endswith("geometry"):
                thermal.update(irradiation_surface_height=4.0, irradiation_stellar_radius_rsun=2.0)
            else:
                thermal["irradiation_factor"] = 0.05
        config = {
            "simulation_parameters": {
                "enable_gas_evolution": True, "enable_photoevaporation": photoev,
                "enable_selfgravity": sg, "enable_dust_drift": dust, "enable_dust_growth": dust,
                "enable_two_dust_populations": False, "omp_num_threads": 4,
            },
            "disk_parameters": {
                "number_of_grid_points": 500, "radial_grid_type": grid,
                "inner_radius_au": 1.0, "outer_radius_au": 50.0,
                "disk_mass": 0.01, "sigma_profile_exponent": -0.5,
                "alpha_viscosity": 0.003, "star_mass_msun": 1.0,
                "aspect_ratio_at_1au": 0.05, "flaring_index": 0.0, "density_floor": 1e-20,
                "photoevaporation_mode": "Picogna", "xray_luminosity_erg_s": 1e30,
            },
            "thermodynamics_parameters": thermal,
            "deadzone_parameters": {
                "deadzone_inner_radius_au": 2.7, "deadzone_outer_radius_au": 24.0,
                "deadzone_inner_transition_width_mult": 1.0,
                "deadzone_outer_transition_width_mult": 1.0, "deadzone_alpha_reduction": 0.01,
            },
            "boundary_conditions": {
                "inner_boundary_condition": "outflow" if energy else "zero_gradient",
                "outer_boundary_condition": "outflow" if energy else "zero_gradient",
            },
            "output_parameters": {
                "output_directory_name": f"output_bench_{name}", "output_format": "ascii",
            },
            "time_parameters": {"total_simulation_time": 5e5, "output_write_frequency": 10000},
            "log_parameters": {"info_level": "info", "disable_terminal_panels": True},
        }
        if dust:
            config["simulation_parameters"]["number_of_dust_particles"] = 1000
            config["disk_parameters"]["dust_density_floor"] = 1e-22
            config["dust_parameters"] = {
                "initial_dust_to_gas_ratio": 0.01, "population_one_mass_ratio": 1.0,
                "one_size_particle_value_cm": 0.01, "dust_particle_density_g_cm3": 1.6,
                "dust_smoothing_mode": "gaussian", "gaussian_smoothing_sigma_grid_units": 1.0,
                "gaussian_smoothing_cutoff_sigma": 3.0,
            }
        destination = directory / f"{name}.yaml"
        destination.write_text(
            "# Generated by generate_configs.py; no grid suffix means linear.\n"
            "# Geometry uses an opaque chi*H surface, including in depleted rings.\n" +
            yaml.safe_dump(config, sort_keys=False)
        )
        paths.append(destination)
    return sorted(paths)


def run_case(path, root, log_directory):
    start = time.perf_counter()
    log_path = log_directory / f"{path.stem}.log"
    environment = {**os.environ, "OMP_NUM_THREADS": "4", "OMP_THREAD_LIMIT": "4",
                   "OPENBLAS_NUM_THREADS": "1", "MKL_NUM_THREADS": "1"}
    with log_path.open("w") as log:
        result = subprocess.run(
            [sys.executable, str(root / "run_simulation.py"), "-c", str(path)],
            cwd=root, env=environment, stdout=log, stderr=subprocess.STDOUT,
        )
    return path.name, result.returncode, time.perf_counter() - start, log_path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generate-only", action="store_true", help="Write YAMLs without launching simulations")
    parser.add_argument("--jobs", type=int, default=10, choices=range(1, 11),
                        metavar="1..10", help="Concurrent runs, each with 4 threads (default: 10)")
    parser.add_argument("--log-dir", type=Path, default=Path("benchmark_logs"),
                        help="Per-run logs and timings.tsv (relative to repository root)")
    args = parser.parse_args()
    directory = Path(__file__).resolve().parent
    root = directory.parent
    paths = generate_configs(directory)
    print(f"Generated {len(paths)} configurations.", flush=True)
    if args.generate_only:
        return 0
    if not (root / "bin" / "simulation").is_file():
        parser.error("bin/simulation is missing; build the release binary with 'make all' first")
    logs = (root / args.log_dir).resolve()
    logs.mkdir(parents=True, exist_ok=True)
    print(f"Running {args.jobs} cases concurrently, at most {args.jobs * 4} OpenMP threads.", flush=True)
    failures = 0
    with (logs / "timings.tsv").open("w") as timings:
        timings.write("configuration\texit_code\twall_seconds\tlog\n")
        with ThreadPoolExecutor(max_workers=args.jobs) as executor:
            futures = [executor.submit(run_case, path, root, logs) for path in paths]
            for future in as_completed(futures):
                name, code, seconds, log = future.result()
                failures += code != 0
                timings.write(f"{name}\t{code}\t{seconds:.6f}\t{log}\n")
                timings.flush()
                print(f"{'OK' if code == 0 else 'FAILED'} {name}: {seconds:.2f}s; log: {log}", flush=True)
    print(f"Finished {len(paths)} cases; failures: {failures}.", flush=True)
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
